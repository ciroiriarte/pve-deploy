ERROR_LITERALS = {"#VALUE!", "#REF!", "#N/A", "#DIV/0!", "#NAME?", "#NUM!", "#NULL!", "#ERROR!"}


@dataclass(frozen=True)
class HardwareHost:
    """A normalized row from the Hardware inventory tab."""

    source: str
    serial: str
    domain: str
    hostname: str
    fqdn: str
    brand: str
    model: str
    ru: str
    notes: str
    role: str | None


@dataclass
class Network:
    """A normalized network column from the Logical Networking Table matrix."""

    name: str
    vrf: str = ""
    vlan_id: int | None = None
    vni_id: int | None = None
    cidr: str = ""
    network_mask: int | None = None
    first_ip: str = ""
    last_ip: str = ""
    gateway: str = ""
    gateway_owner: str = ""
    dhcp_range: str = ""
    mtu: int | None = None
    # Per-subnet service addresses. Lists rather than scalars because a subnet may
    # legitimately carry several, even where the sheet currently holds one. Empty
    # is normal and never a warning: the isolated storage segments have neither a
    # resolver nor an NTP server, by design.
    dns_resolvers: list[str] = field(default_factory=list)
    ntp_servers: list[str] = field(default_factory=list)
    role_bonds: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True)
class CablingPort:
    """A normalized cabling plan row."""

    host: str
    slot: str
    module: str
    port: str
    type: str
    os_device: str
    bond: str
    peer: str
    peer_port: str
    peer_aggregation: str
    note: str


@dataclass
class ParsedModel:
    """The complete normalized spreadsheet model used to render inventory files."""

    spreadsheet_id: str
    hardware: dict[str, HardwareHost]
    networks: dict[str, Network]
    host_ips: dict[str, dict[str, str]]
    cabling: dict[str, list[CablingPort]]
    segments: list[dict[str, str]]
    tab_row_counts: dict[str, int]
    warnings: list[str] = field(default_factory=list)


class Color:
    """Small ANSI color helper whose output can be disabled."""

    def __init__(self, enabled: bool) -> None:
        """Create a color helper."""
        self.enabled = enabled

    def red(self, text: str) -> str:
        """Return red text when color is enabled."""
        return self._wrap("31", text)

    def green(self, text: str) -> str:
        """Return green text when color is enabled."""
        return self._wrap("32", text)

    def yellow(self, text: str) -> str:
        """Return yellow text when color is enabled."""
        return self._wrap("33", text)

    def cyan(self, text: str) -> str:
        """Return cyan text when color is enabled."""
        return self._wrap("36", text)

    def _wrap(self, code: str, text: str) -> str:
        """Wrap text in an ANSI escape sequence when enabled."""
        if not self.enabled:
            return text
        return f"\033[{code}m{text}\033[0m"


def cell(row: list[str], index: int) -> str:
    """Safely read a trimmed cell from a possibly ragged Sheets API row."""
    if index < 0 or index >= len(row):
        return ""
    return str(row[index]).strip()


def normalize_key(value: str) -> str:
    """Normalize a sheet header or label for tolerant matching."""
    return re.sub(r"\s+", " ", value.strip()).casefold()


def slug(value: str) -> str:
    """Convert a free-form value into a stable lowercase identifier."""
    out = re.sub(r"[^a-zA-Z0-9]+", "_", value.strip().lower()).strip("_")
    return out or "unknown"


def parse_int(value: str) -> int | None:
    """Parse an integer from a sheet cell, returning None for blanks and placeholders."""
    text = value.strip()
    if not text or text == "-":
        return None
    try:
        return int(text)
    except ValueError:
        return None


# Cell values that name an allocation method instead of a literal address. These are
# valid assignments and must not be validated as IP addresses.
NON_ADDRESS_ASSIGNMENTS = {"dhcp", "slaac", "auto", "-"}


def is_error_literal(value: str) -> bool:
    """Return True when a sheet cell contains a spreadsheet formula error literal."""
    return value.strip().upper() in ERROR_LITERALS


def is_missing(value: str) -> bool:
    """Return True when a sheet cell means blank, not applicable, or broken/missing."""
    text = value.strip()
    return not text or text == "-" or is_error_literal(text)


def parse_address_list(value: str) -> list[str]:
    """Split a cell holding one or more service addresses.

    Tolerant of the separators a spreadsheet actually collects over time -- commas,
    semicolons, newlines, plain spaces -- because the column is typed by hand and a
    second server will eventually be appended in whatever style the author prefers.
    """
    if is_missing(value):
        return []
    return [part for part in re.split(r"[,;\s]+", value.strip()) if part and part != "-"]


def infer_role(hostname: str, brand: str, model: str) -> str | None:
    """Infer the deployment role for a hardware row from naming and server model conventions."""
    name = hostname.casefold()
    model_text = model.casefold()
    brand_text = brand.casefold()
    if "-pve-" in name:
        return "hci"
    if "-bkp-" in name or "-pbs-" in name:
        return "bkp"
    if "saph" in name or "sap" in name:
        return "saph-db"
    if "lenovo" in brand_text and "thinksystem" in model_text:
        return "server"
    return None


def short_hostname(fqdn_or_host: str) -> str:
    """Return the short host name from an FQDN or already-short host string."""
    return fqdn_or_host.strip().split(".", 1)[0]


def canonical_host_key(value: str) -> str:
    """Return the canonical short hostname key used to join tabs."""
    return short_hostname(value).casefold()


def load_credentials(client_secret: str, token_path: str) -> Any:
    """Resolve Google credentials, preferring ADC and falling back to InstalledAppFlow OAuth."""
    try:
        import google.auth
        from google.auth.transport.requests import Request
    except ImportError as exc:
        raise SystemExit(
            "ERROR: missing Google auth libraries. Install google-auth, google-auth-oauthlib, "
            "and google-api-python-client."
        ) from exc

    try:
        creds, _ = google.auth.default(scopes=[SHEETS_SCOPE])
        if creds and creds.expired and creds.refresh_token:
            creds.refresh(Request())
        return creds
    except Exception:
        pass

    try:
        from google.auth.transport.requests import Request
        from google.oauth2.credentials import Credentials
        from google_auth_oauthlib.flow import InstalledAppFlow
    except ImportError as exc:
        raise SystemExit(
            "ERROR: missing OAuth libraries. Install google-auth-oauthlib and google-api-python-client."
        ) from exc

    token_file = Path(token_path)
    creds = None
    if token_file.exists():
        creds = Credentials.from_authorized_user_file(str(token_file), [SHEETS_SCOPE])
    if creds and creds.expired and creds.refresh_token:
        creds.refresh(Request())
    if not creds or not creds.valid:
        secret_file = Path(client_secret)
        if not secret_file.exists():
            raise SystemExit(f"ERROR: OAuth client secret not found: {secret_file}")
        flow = InstalledAppFlow.from_client_secrets_file(str(secret_file), [SHEETS_SCOPE])
        creds = flow.run_local_server(port=0)
        token_file.parent.mkdir(parents=True, exist_ok=True)
        token_file.write_text(creds.to_json(), encoding="utf-8")
    return creds


def build_sheets_service(client_secret: str, token_path: str) -> Any:
    """Build an authenticated Google Sheets API service."""
    try:
        from googleapiclient.discovery import build
    except ImportError as exc:
        raise SystemExit("ERROR: missing google-api-python-client.") from exc
    return build("sheets", "v4", credentials=load_credentials(client_secret, token_path))


def read_range(service: Any, spreadsheet_id: str, tab: str) -> list[list[str]]:
    """Read one tab with A1 notation using spreadsheets().values().get()."""
    result = (
        service.spreadsheets()
        .values()
        .get(spreadsheetId=spreadsheet_id, range=f"{tab}!{READ_RANGE}")
        .execute()
    )
    return result.get("values", [])


def list_tabs(service: Any, spreadsheet_id: str) -> list[str]:
    """Return sheet tab names from spreadsheet metadata."""
    meta = service.spreadsheets().get(spreadsheetId=spreadsheet_id).execute()
    return [sheet["properties"]["title"] for sheet in meta.get("sheets", [])]


def header_index(header: list[str]) -> dict[str, int]:
    """Build a normalized header-to-index map."""
    return {normalize_key(name): idx for idx, name in enumerate(header) if name.strip()}


def require_column(index: dict[str, int], name: str) -> int:
    """Return a required column index or abort with a clear error."""
    key = normalize_key(name)
    if key not in index:
        raise SystemExit(f"ERROR: required sheet column missing: {name}")
    return index[key]


def parse_hardware(rows: list[list[str]], warnings: list[str]) -> dict[str, HardwareHost]:
    """Parse the Hardware inventory tab into server-oriented hardware rows."""
    if not rows:
        return {}
    idx = header_index(rows[0])
    columns = {
        "source": require_column(idx, "Source"),
        "serial": require_column(idx, "Serial Number"),
        "domain": require_column(idx, "Domain"),
        "hostname": require_column(idx, "Hostname"),
        "fqdn": require_column(idx, "FQDN"),
        "brand": require_column(idx, "Brand"),
        "model": require_column(idx, "Model"),
        "ru": require_column(idx, "RU"),
        "notes": require_column(idx, "Notes"),
    }

    hosts: dict[str, HardwareHost] = {}
    for row_no, row in enumerate(rows[1:], start=2):
        hostname = cell(row, columns["hostname"])
        fqdn = cell(row, columns["fqdn"])
        if not hostname and not fqdn:
            continue
        brand = cell(row, columns["brand"])
        model = cell(row, columns["model"])
        role = infer_role(hostname, brand, model)
        if role is None:
            continue
        fqdn = fqdn or f"{hostname}.{cell(row, columns['domain'])}".strip(".")
        item = HardwareHost(
            source=cell(row, columns["source"]),
            serial=cell(row, columns["serial"]),
            domain=cell(row, columns["domain"]),
            hostname=hostname,
            fqdn=fqdn,
            brand=brand,
            model=model,
            ru=cell(row, columns["ru"]),
            notes=cell(row, columns["notes"]),
            role=role,
        )
        key = canonical_host_key(hostname or fqdn)
        if key in hosts:
            warnings.append(f"Hardware inventory row {row_no}: duplicate server hostname {hostname!r}; last row wins")
        hosts[key] = item
    return hosts


def role_service_addresses(
    model: ParsedModel, role: str, warnings: list[str]
) -> tuple[list[str], list[str]]:
    """Resolvers and NTP servers for the subnets a role actually attaches to.

    Derived rather than hardcoded to a network name: a role's hosts should use the
    services published on the subnets they are on, and on this sheet only the
    management-facing subnets carry them -- the storage segments are deliberately
    blank. So the filter selects the right subnet without the tool needing to know
    that "PVE Management" is the special one.

    A disagreement between two subnets of the same role is reported rather than
    silently merged: the union would configure hosts with a resolver that is only
    correct on a network they are not asking questions from.
    """
    dns: list[str] = []
    ntp: list[str] = []
    per_net: dict[str, tuple[tuple[str, ...], tuple[str, ...]]] = {}
    for name, net in sorted(model.networks.items()):
        if role not in net.role_bonds:
            continue
        if not net.dns_resolvers and not net.ntp_servers:
            continue
        per_net[name] = (tuple(net.dns_resolvers), tuple(net.ntp_servers))
        for addr in net.dns_resolvers:
            if addr not in dns:
                dns.append(addr)
        for addr in net.ntp_servers:
            if addr not in ntp:
                ntp.append(addr)

    distinct = set(per_net.values())
    if len(distinct) > 1:
        detail = "; ".join(
            f"{n}: dns={list(d) or '-'} ntp={list(t) or '-'}" for n, (d, t) in sorted(per_net.items())
        )
        warnings.append(
            f"Role {role!r}: subnets disagree on DNS/NTP, using the union. {detail}"
        )
    return dns, ntp


def role_key_from_label(label: str) -> str | None:
    """Map a Logical Networking Table role row label to a compact role key."""
    text = normalize_key(label)
    if text.startswith("hci "):
        return "hci"
    if text.startswith("bkp "):
        return "bkp"
    if text.startswith(("saph-db ", "sap ")):
        return "saph-db"
    return None


def parse_logical_networking(rows: list[list[str]], warnings: list[str]) -> tuple[dict[str, Network], dict[str, dict[str, str]]]:
    """Parse the transposed Logical Networking Table into networks and host IP assignments."""
    if not rows:
        return {}, {}
    header = rows[0]
    network_names = [cell(header, idx) for idx in range(1, len(header))]
    networks = {name: Network(name=name) for name in network_names if name}

    hostname_row_index: int | None = None
    attr_rows: list[list[str]] = []
    for idx, row in enumerate(rows[1:], start=1):
        label = cell(row, 0)
        if normalize_key(label) == "hostname":
            hostname_row_index = idx
            break
        attr_rows.append(row)

    attr_map = {normalize_key(cell(row, 0)): row for row in attr_rows if cell(row, 0)}

    for col_idx, name in enumerate(network_names, start=1):
        if not name:
            continue
        net = networks[name]
        net.vrf = cell(attr_map.get("vrf", []), col_idx)
        net.vlan_id = parse_int(cell(attr_map.get("vlan tag", []), col_idx))
        net.vni_id = parse_int(cell(attr_map.get("vni tag", []), col_idx))
        net.cidr = clean_used_value(cell(attr_map.get("segment", []), col_idx), warnings, f"{name} Segment")
        net.network_mask = parse_int(cell(attr_map.get("network mask", []), col_idx))
        net.first_ip = clean_used_value(cell(attr_map.get("first ip in subnet", []), col_idx), warnings, f"{name} First IP in subnet")
        net.last_ip = clean_used_value(cell(attr_map.get("last ip in subnet", []), col_idx), warnings, f"{name} Last IP in subnet")
        net.gateway = clean_optional_value(cell(attr_map.get("gateway ip", []), col_idx), warnings, f"{name} Gateway IP")
        net.gateway_owner = cell(attr_map.get("gateway node", []), col_idx)
        net.dhcp_range = cell(attr_map.get("dhcp range", []), col_idx)
        net.mtu = parse_int(cell(attr_map.get("mtu", []), col_idx))
        if net.mtu is None:
            warnings.append(f"Network {name!r}: missing MTU")
        # No warning when absent, unlike MTU: only the management-facing subnets
        # carry these, and corosync, live migration, underlay and both ceph
        # segments are meant to have neither.
        net.dns_resolvers = parse_address_list(cell(attr_map.get("dns resolver", []), col_idx))
        net.ntp_servers = parse_address_list(cell(attr_map.get("ntp", []), col_idx))

    ignored_labels = {
        "ne ips",
        "ip: usable/capacity",
        "ip: used",
        "ip: free",
    }
    for row in attr_rows:
        label = cell(row, 0)
        label_key = normalize_key(label)
        if label_key in ignored_labels:
            continue
        role_key = role_key_from_label(label)
        if not role_key:
            continue
        for col_idx, name in enumerate(network_names, start=1):
            bond = cell(row, col_idx)
            if name and not is_missing(bond):
                networks[name].role_bonds[role_key] = bond

    host_ips: dict[str, dict[str, str]] = {}
    if hostname_row_index is not None:
        for row_no, row in enumerate(rows[hostname_row_index + 1 :], start=hostname_row_index + 2):
            host = cell(row, 0)
            if not host:
                break
            host_key = canonical_host_key(host)
            assignments: dict[str, str] = {}
            for col_idx, name in enumerate(network_names, start=1):
                ip = cell(row, col_idx)
                if not name or is_missing(ip):
                    if is_error_literal(ip):
                        warnings.append(f"Logical Networking Table row {row_no}, network {name!r}: spreadsheet error {ip}")
                    continue
                if is_error_literal(ip):
                    warnings.append(f"Logical Networking Table row {row_no}, network {name!r}: spreadsheet error {ip}")
                    assignments[name] = ip
                else:
                    assignments[name] = ip
            if assignments:
                host_ips[host_key] = assignments

    return networks, host_ips


def clean_used_value(value: str, warnings: list[str], where: str) -> str:
    """Return a validation-critical value while preserving error literals for fail-closed checks."""
    if is_error_literal(value):
        warnings.append(f"{where}: spreadsheet error {value}")
        return value
    return "" if value == "-" else value


def clean_optional_value(value: str, warnings: list[str], where: str) -> str:
    """Return an optional generated value, treating placeholders and sheet errors as blank."""
    if is_error_literal(value):
        warnings.append(f"{where}: spreadsheet error {value}")
        return value
    return "" if value == "-" else value


def parse_cabling(rows: list[list[str]], warnings: list[str]) -> dict[str, list[CablingPort]]:
    """Parse the Cabling tab into a per-host cabling plan."""
    if not rows:
        return {}
    idx = header_index(rows[0])
    columns = {
        "host": require_column(idx, "Host"),
        "slot": require_column(idx, "Slot"),
        "module": require_column(idx, "Module"),
        "port": require_column(idx, "Port"),
        "type": require_column(idx, "Type"),
        "os_device": require_column(idx, "OS Device"),
        "bond": require_column(idx, "Aggregation"),
        "peer": require_column(idx, "Peer"),
        "peer_port": require_column(idx, "Peer port"),
        "peer_aggregation": require_column(idx, "Peer aggregation"),
        "note": require_column(idx, "Note"),
    }

    cabling: dict[str, list[CablingPort]] = {}
    for row in rows[1:]:
        host = cell(row, columns["host"])
        if not host:
            continue
        item = CablingPort(
            host=host,
            slot=cell(row, columns["slot"]),
            module=cell(row, columns["module"]),
            port=cell(row, columns["port"]),
            type=cell(row, columns["type"]),
            os_device=cell(row, columns["os_device"]),
            bond=cell(row, columns["bond"]),
            peer=cell(row, columns["peer"]),
            peer_port=cell(row, columns["peer_port"]),
            peer_aggregation=cell(row, columns["peer_aggregation"]),
            note=cell(row, columns["note"]),
        )
        cabling.setdefault(canonical_host_key(host), []).append(item)
    return cabling


def parse_segments(rows: list[list[str]]) -> list[dict[str, str]]:
    """Parse meaningful rows from the Spanish Segments tab."""
    if not rows:
        return []
    idx = header_index(rows[0])
    vlan_col = idx.get(normalize_key("VLAN"))
    segment_col = idx.get(normalize_key("Segmento"))
    if vlan_col is None or segment_col is None:
        return []
    headers = [cell(rows[0], i) for i in range(len(rows[0]))]
    parsed: list[dict[str, str]] = []
    for row in rows[1:]:
        if not cell(row, vlan_col) or not cell(row, segment_col):
            continue
        parsed.append({headers[i]: cell(row, i) for i in range(len(headers)) if headers[i]})
    return parsed


def fetch_model(service: Any, spreadsheet_id: str) -> ParsedModel:
    """Read all required tabs and return the normalized model."""
    warnings: list[str] = []
    tab_names = ["Hardware inventory", "Logical Networking Table", "Cabling", "Segments"]
    raw = {tab: read_range(service, spreadsheet_id, tab) for tab in tab_names}
    hardware = parse_hardware(raw["Hardware inventory"], warnings)
    networks, host_ips = parse_logical_networking(raw["Logical Networking Table"], warnings)
    cabling = parse_cabling(raw["Cabling"], warnings)
    segments = parse_segments(raw["Segments"])

    # Compare against every hostname present in the Hardware inventory tab, not just the
    # rows that survived server-role filtering. Switches, PDUs, UPSs and firewalls are
    # legitimately in the sheet but are not deployment targets, so warning about them
    # produces noise that buries genuine hostname mismatches.
    known_hostnames: set[str] = set()
    hw_rows = raw["Hardware inventory"]
    if hw_rows:
        hw_idx = header_index(hw_rows[0])
        hostname_col = require_column(hw_idx, "Hostname")
        for row in hw_rows[1:]:
            name = cell(row, hostname_col)
            if name:
                known_hostnames.add(name)

    for host_key in cabling:
        if host_key not in hardware and host_key not in known_hostnames:
            warnings.append(f"Cabling references host {host_key!r}, but it is absent from Hardware inventory")

    for name in networks:
        used = any(name in assignments for assignments in host_ips.values())
        if not used:
            warnings.append(f"Network {name!r}: no hosts have assigned IPs")

    return ParsedModel(
        spreadsheet_id=spreadsheet_id,
        hardware=hardware,
        networks=networks,
        host_ips=host_ips,
        cabling=cabling,
        segments=segments,
        tab_row_counts={tab: len(rows) for tab, rows in raw.items()},
        warnings=warnings,
    )


def validate(model: ParsedModel) -> list[str]:
    """Run fail-closed invariant checks and return human-readable violations."""
    violations: list[str] = []
    parsed_networks: dict[str, ipaddress._BaseNetwork] = {}

    for name, net in model.networks.items():
        if net.vlan_id is not None and not net.cidr:
            violations.append(f"Network {name!r} has VLAN {net.vlan_id} but no CIDR")
        if net.cidr:
            if is_error_literal(net.cidr):
                violations.append(f"Network {name!r} has spreadsheet error in CIDR: {net.cidr}")
                continue
            try:
                parsed = ipaddress.ip_network(net.cidr, strict=False)
                parsed_networks[name] = parsed
                if net.network_mask is not None and net.network_mask != parsed.prefixlen:
                    violations.append(
                        f"Network {name!r} mask mismatch: Network Mask={net.network_mask}, CIDR prefix={parsed.prefixlen}"
                    )
            except ValueError as exc:
                violations.append(f"Network {name!r} has invalid CIDR {net.cidr!r}: {exc}")
        # Only fields the generated inventory actually consumes can refuse a run.
        # "First IP in subnet" / "Last IP in subnet" are derived convenience columns in
        # the sheet; a broken formula there is already reported as a parse warning and
        # must not block a deployment.
        if is_error_literal(net.gateway):
            violations.append(f"Network {name!r} has spreadsheet error in used field gateway: {net.gateway}")

    seen_ips: dict[tuple[str, str], str] = {}
    for host_key, assignments in model.host_ips.items():
        for network_name, ip_text in assignments.items():
            if is_error_literal(ip_text):
                violations.append(f"Host {host_key!r} has spreadsheet error as IP on {network_name!r}: {ip_text}")
                continue
            # "dhcp" is a legitimate assignment, not a malformed address: the OOBM BMC
            # segment is DHCP-managed with static reservations, so the sheet records the
            # allocation method rather than a literal address.
            if ip_text.strip().lower() in NON_ADDRESS_ASSIGNMENTS:
                continue
            try:
                ip = ipaddress.ip_address(ip_text)
            except ValueError as exc:
                violations.append(f"Host {host_key!r} has invalid IP {ip_text!r} on {network_name!r}: {exc}")
                continue
            if network_name in parsed_networks and ip not in parsed_networks[network_name]:
                violations.append(
                    f"Host {host_key!r} IP {ip_text} is outside {network_name!r} CIDR {parsed_networks[network_name]}"
                )
            seen_key = (network_name, ip_text)
            if seen_key in seen_ips:
                violations.append(
                    f"Duplicate IP {ip_text} on network {network_name!r}: hosts {seen_ips[seen_key]!r} and {host_key!r}"
                )
            else:
                seen_ips[seen_key] = host_key

    mapped_bonds = {
        bond
        for net in model.networks.values()
        for bond in net.role_bonds.values()
        if bond
    }
    # Only deployment targets are in scope. Firewalls and switches appear in the Cabling
    # tab with device-specific aggregation names (LACP01, "-") that have no PVE role
    # mapping by design; refusing on them would make validate() unpassable, and a gate
    # that can never pass is a gate operators learn to bypass.
    in_scope_roles = {"hci", "bkp", "saph-db", "server"}
    for host_key, ports in model.cabling.items():
        host = model.hardware.get(host_key)
        if host is None or host.role not in in_scope_roles:
            continue
        for port in ports:
            if port.bond and port.bond not in mapped_bonds:
                violations.append(
                    f"Cabling host {host_key!r} names bond {port.bond!r}, but no network role mapping uses that bond"
                )

    bmc_networks = [name for name, net in model.networks.items() if any(bond == "BMC" for bond in net.role_bonds.values())]
    for host_key, host in model.hardware.items():
        if host.role and host.role in {"hci", "bkp", "saph-db", "server"}:
            bmc_ip = find_bmc_ip(model, host_key, bmc_networks)
            if not bmc_ip:
                violations.append(f"Server host {host.hostname!r} has no BMC IP assignment")

    return violations


def find_bmc_ip(model: ParsedModel, host_key: str, bmc_networks: list[str] | None = None) -> str:
    """Return the BMC IP for a host by inspecting networks mapped to the BMC bond."""
    networks = bmc_networks
    if networks is None:
        networks = [name for name, net in model.networks.items() if any(bond == "BMC" for bond in net.role_bonds.values())]
    assignments = model.host_ips.get(host_key, {})
    for network in networks:
        ip = assignments.get(network, "")
        if ip and not is_missing(ip):
            return ip
    return ""


def host_primary_ip(model: ParsedModel, host_key: str, role: str | None) -> str:
    """Return the best Ansible management IP for a host."""
    preferred_roles = [role] if role else []
    if role == "server":
        preferred_roles = ["hci", "bkp", "saph-db"]
    for role_key in preferred_roles:
        for name, net in model.networks.items():
            if net.role_bonds.get(role_key) == "bond0":
                ip = model.host_ips.get(host_key, {}).get(name, "")
                if ip and not is_missing(ip):
                    return ip
    for name, ip in model.host_ips.get(host_key, {}).items():
        net = model.networks.get(name)
        if net and any(bond != "BMC" for bond in net.role_bonds.values()) and not is_missing(ip):
            return ip
    return ""


def to_plain_model(model: ParsedModel) -> dict[str, Any]:
    """Convert dataclasses into JSON-serializable plain structures."""
    return {
        "spreadsheet_id": model.spreadsheet_id,
        "hardware": {key: dataclasses.asdict(value) for key, value in sorted(model.hardware.items())},
        "networks": {key: dataclasses.asdict(value) for key, value in sorted(model.networks.items())},
        "host_ips": {key: dict(sorted(value.items())) for key, value in sorted(model.host_ips.items())},
        "cabling": {
            key: [dataclasses.asdict(port) for port in ports]
            for key, ports in sorted(model.cabling.items())
        },
        "segments": model.segments,
        "tab_row_counts": model.tab_row_counts,
        "warnings": model.warnings,
    }


def render_inventory_tree(model: ParsedModel, env: str) -> dict[str, str]:
    """Render all generated inventory files as a path-to-content mapping."""
    base = Path("inventories") / env
    files: dict[str, str] = {}

    files[str(base / "hosts.yml")] = header("Hardware inventory, Logical Networking Table") + dump_yaml(
        build_hosts_inventory(model)
    )
    # group_vars uses the DIRECTORY form (group_vars/<group>/generated.yml) rather than
    # a flat <group>.yml. Ansible loads every file in the directory, so hand-maintained
    # material -- above all group_vars/bmc/vault.yml holding the BMC credentials -- can
    # live alongside generated content without this tool overwriting it on the next
    # sync. Ansible does not permit both group_vars/bmc.yml and group_vars/bmc/ to
    # exist, so the choice has to be made here, and only the directory form leaves room
    # for secrets.
    files[str(base / "group_vars" / "all" / "generated.yml")] = header(
        "Logical Networking Table, Segments"
    ) + dump_yaml({"network_catalog": build_network_catalog(model)})
    # Service addresses land in group_vars/pve rather than group_vars/all because
    # only pve_baseline consumes them, via chrony.conf.j2 and resolv.conf.j2, and
    # the bmc group connects locally and has no use for them. The group scope also
    # settles precedence: group_vars/<group> outranks group_vars/all whatever the
    # filenames are, so these win over any stale hand-maintained copy.
    pve_dns, pve_ntp = role_service_addresses(model, "hci", model.warnings)
    files[str(base / "group_vars" / "pve" / "generated.yml")] = header("Logical Networking Table") + dump_yaml(
        {
            "pve_role": "hci",
            "pve_management_bond": "bond0",
            "pve_expected_networks": role_networks(model, "hci"),
            "dns_servers": pve_dns,
            "ntp_servers": pve_ntp,
        }
    )
    files[str(base / "group_vars" / "bmc" / "generated.yml")] = header("Logical Networking Table") + dump_yaml(
        {
            "ansible_connection": "local",
            "bmc_role": "out_of_band_management",
            "bmc_expected_networks": role_networks_by_bond(model, "BMC"),
        }
    )

    for host_key, host in sorted(model.hardware.items()):
        files[str(base / "host_vars" / f"{host.hostname}.yml")] = header(
            "Hardware inventory, Logical Networking Table, Cabling"
        ) + dump_yaml(build_host_vars(model, host_key, host))

    provisional = dict(files)
    provenance_path = str(base / ".sheet-sync.json")
    provenance = build_provenance(model, provisional, load_previous_provenance(Path(provenance_path)))
    files[provenance_path] = json.dumps(provenance, indent=2, sort_keys=True) + "\n"
    return files


def header(tabs: str) -> str:
    """Return the standard generated-file YAML header."""
    return GENERATED_HEADER.format(tabs=tabs)


def build_hosts_inventory(model: ParsedModel) -> dict[str, Any]:
    """Build the Ansible hosts.yml inventory structure."""
    pve_hosts: dict[str, Any] = {}
    pbs_hosts: dict[str, Any] = {}
    bmc_hosts: dict[str, Any] = {}

    for host_key, host in sorted(model.hardware.items()):
        primary_ip = host_primary_ip(model, host_key, host.role)
        entry: dict[str, Any] = {"ansible_host": primary_ip or host.fqdn}
        if host.fqdn:
            entry["fqdn"] = host.fqdn
        if host.role == "hci":
            pve_hosts[host.hostname] = entry
        elif host.role == "bkp":
            pbs_hosts[host.hostname] = entry

        bmc_ip = find_bmc_ip(model, host_key)
        if bmc_ip:
            bmc_hosts[f"{host.hostname}-bmc"] = {
                "ansible_host": bmc_ip,
                "ansible_connection": "local",
                "parent_host": host.hostname,
            }

    return {
        "all": {
            "children": {
                "pve": {"hosts": pve_hosts},
                "pbs": {"hosts": pbs_hosts},
                "bmc": {"hosts": bmc_hosts},
            }
        }
    }


def build_network_catalog(model: ParsedModel) -> dict[str, Any]:
    """Build the network catalog for group_vars/all.yml."""
    catalog: dict[str, Any] = {}
    for name, net in sorted(model.networks.items()):
        catalog[slug(name)] = {
            "name": net.name,
            "vrf": net.vrf,
            "vlan_id": net.vlan_id,
            "vni_id": net.vni_id,
            "cidr": net.cidr,
            "mtu": net.mtu,
            "gateway": net.gateway,
            "gateway_owner": net.gateway_owner,
            "dhcp_range": net.dhcp_range,
            "dns_resolvers": list(net.dns_resolvers),
            "ntp_servers": list(net.ntp_servers),
            "role_bonds": dict(sorted(net.role_bonds.items())),
        }
    return catalog


def role_networks(model: ParsedModel, role: str) -> dict[str, str]:
    """Return network-name-to-bond mappings for one role."""
    return {
        slug(name): net.role_bonds[role]
        for name, net in sorted(model.networks.items())
        if role in net.role_bonds
    }


def role_networks_by_bond(model: ParsedModel, bond: str) -> list[str]:
    """Return network slugs carried by a specific bond label."""
    return [
        slug(name)
        for name, net in sorted(model.networks.items())
        if bond in net.role_bonds.values()
    ]


def build_host_vars(model: ParsedModel, host_key: str, host: HardwareHost) -> dict[str, Any]:
    """Build one host_vars file from hardware, IP assignments, and cabling rows."""
    assignments = model.host_ips.get(host_key, {})
    networks = {
        slug(name): {
            "name": name,
            "ip": ip,
            "cidr": model.networks[name].cidr if name in model.networks else "",
            "vlan_id": model.networks[name].vlan_id if name in model.networks else None,
            "bond": model.networks[name].role_bonds.get(host.role or "", "") if name in model.networks else "",
        }
        for name, ip in sorted(assignments.items())
        if not is_missing(ip)
    }
    cabling = [
        {
            "slot": port.slot,
            "module": port.module,
            "port": port.port,
            "type": port.type,
            "os_device": port.os_device,
            "bond": port.bond,
            "peer": port.peer,
            "peer_port": port.peer_port,
            "peer_aggregation": port.peer_aggregation,
            "note": port.note,
        }
        for port in model.cabling.get(host_key, [])
    ]
    return {
        "fqdn": host.fqdn,
        # NOT "serial": that is a reserved Ansible play keyword (rolling-batch size),
        # and using it as a host variable makes ansible-inventory warn and risks
        # shadowing the keyword in a play.
        "hardware_serial": host.serial,
        "brand": host.brand,
        "model": host.model,
        "hardware_role": host.role,
        "bmc_ip": find_bmc_ip(model, host_key),
        "networks": networks,
        "cabling": cabling,
    }


def build_provenance(
    model: ParsedModel,
    files_without_provenance: dict[str, str],
    previous: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Build the .sheet-sync.json provenance document.

    `synced_at` is carried over from the previous provenance file when the content
    digest is unchanged. Stamping a fresh timestamp on every run would make `diff`
    report a difference even when nothing changed, which would destroy its value as a
    drift detector and produce a no-op commit on every sync. The timestamp therefore
    records when the inventory last actually changed, not when the tool last ran.
    """
    digest = hashlib.sha256()
    for path in sorted(files_without_provenance):
        digest.update(path.encode("utf-8"))
        digest.update(b"\0")
        digest.update(files_without_provenance[path].encode("utf-8"))
        digest.update(b"\0")
    tree_sha256 = digest.hexdigest()

    synced_at = dt.datetime.now(dt.UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    if previous and previous.get("tree_sha256") == tree_sha256 and previous.get("synced_at"):
        synced_at = str(previous["synced_at"])

    return {
        "spreadsheet_id": model.spreadsheet_id,
        "tab_row_counts": model.tab_row_counts,
        "synced_at": synced_at,
        "tree_sha256": tree_sha256,
    }


def load_previous_provenance(path: Path) -> dict[str, Any] | None:
    """Read the existing provenance file, returning None when absent or unreadable."""
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def dump_yaml(value: Any) -> str:
    """Serialize simple Python data as deterministic YAML, using PyYAML when available."""
    try:
        import yaml  # type: ignore
    except ImportError:
        return dump_yaml_fallback(value) + "\n"
    return yaml.safe_dump(value, sort_keys=True, default_flow_style=False, allow_unicode=False)


def dump_yaml_fallback(value: Any, indent: int = 0) -> str:
    """Serialize dictionaries, lists, scalars, and None as minimal deterministic YAML."""
    prefix = " " * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines: list[str] = []
        for key in sorted(value):
            child = value[key]
            rendered_key = yaml_scalar(str(key))
            if isinstance(child, (dict, list)) and child:
                lines.append(f"{prefix}{rendered_key}:")
                lines.append(dump_yaml_fallback(child, indent + 2))
            else:
                lines.append(f"{prefix}{rendered_key}: {dump_yaml_fallback(child, 0)}")
        return "\n".join(lines)
    if isinstance(value, list):
        if not value:
            return "[]"
        lines = []
        for item in value:
            if isinstance(item, (dict, list)) and item:
                lines.append(f"{prefix}-")
                lines.append(dump_yaml_fallback(item, indent + 2))
            else:
                lines.append(f"{prefix}- {dump_yaml_fallback(item, 0)}")
        return "\n".join(lines)
    return yaml_scalar(value)


def yaml_scalar(value: Any) -> str:
    """Render one scalar for the fallback YAML serializer."""
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, int):
        return str(value)
    text = str(value)
    if text == "":
        return '""'
    if re.fullmatch(r"[A-Za-z0-9_./:-]+", text) and text not in {"true", "false", "null", "yes", "no"}:
        return text
    return json.dumps(text)


def render_diff(root: Path, rendered: dict[str, str], color: Color) -> tuple[bool, str]:
    """Return whether files differ plus a unified diff for all rendered paths."""
    chunks: list[str] = []
    changed = False
    for rel_path in sorted(rendered):
        target = root / rel_path
        old = target.read_text(encoding="utf-8") if target.exists() else ""
        new = rendered[rel_path]
        if old == new:
            continue
        changed = True
        old_lines = old.splitlines(keepends=True)
        new_lines = new.splitlines(keepends=True)
        diff = difflib.unified_diff(
            old_lines,
            new_lines,
            fromfile=str(target),
            tofile=str(target),
            lineterm="",
        )
        for line in diff:
            if line.startswith("+") and not line.startswith("+++"):
                chunks.append(color.green(line))
            elif line.startswith("-") and not line.startswith("---"):
                chunks.append(color.red(line))
            elif line.startswith("@@"):
                chunks.append(color.cyan(line))
            else:
                chunks.append(line)
            if not line.endswith("\n"):
                chunks[-1] += "\n"
    return changed, "".join(chunks)


def print_warnings(warnings: list[str], color: Color) -> None:
    """Print parser and validation warnings."""
    for warning in warnings:
        print(color.yellow(f"WARNING: {warning}"), file=sys.stderr)


def write_files(root: Path, rendered: dict[str, str]) -> int:
    """Write rendered files, returning 0 on success and 3 if a write fails partway."""
    try:
        for rel_path, content in sorted(rendered.items()):
            target = root / rel_path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            print(f"wrote {target}")
    except OSError as exc:
        print(f"ERROR: write failed: {exc}", file=sys.stderr)
        return 3
    return 0


def confirm_apply(assume_yes: bool = False) -> bool:
    """Require confirmation before mutating files.

    Interactive by default. `--yes` is the documented non-interactive escape hatch for
    CI and scripted runs; without it a non-TTY invocation refuses rather than silently
    writing, so a pipeline can never mutate the inventory by accident.
    """
    if assume_yes:
        print("Confirmation bypassed with --yes.")
        return True
    if not sys.stdin.isatty():
        print(
            "ERROR: sync --apply needs an interactive terminal to confirm. "
            "Pass --yes for a non-interactive run.",
            file=sys.stderr,
        )
        return False
    answer = input('Type "yes" to write generated inventory files: ').strip()
    return answer == "yes"


def build_parser() -> argparse.ArgumentParser:
    """Build the command-line argument parser."""
    parser = argparse.ArgumentParser(
        prog="tools/sheet_sync.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    # Global options are accepted both before and after the subcommand. Plain
    # argparse globals must precede it ("--json show"), which is not what anyone
    # types; the natural form is "show --json".
    #
    # The top-level copies carry the real defaults. The per-subcommand copies use
    # argparse.SUPPRESS so that an option the user did not pass is simply absent
    # from the namespace, instead of a default that would overwrite a value given
    # before the subcommand.
    parser.add_argument("--env", default="", help="inventory site name, e.g. --env example (required)")
    parser.add_argument("--root", default=".", help="repository root path (default: current directory)")
    parser.add_argument("--json", action="store_true", help="emit machine-readable JSON where supported")
    parser.add_argument("--no-color", action="store_true", help="disable ANSI colors")

    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--env", default=argparse.SUPPRESS, help="inventory site name, e.g. --env example (required)")
    common.add_argument("--root", default=argparse.SUPPRESS, help="repository root path (default: current directory)")
    common.add_argument(
        "--json", action="store_true", default=argparse.SUPPRESS, help="emit machine-readable JSON where supported"
    )
    common.add_argument(
        "--no-color", action="store_true", default=argparse.SUPPRESS, help="disable ANSI colors"
    )

    sub = parser.add_subparsers(dest="action", required=True)
    sub.add_parser("tabs", parents=[common], help="list spreadsheet tabs and exit")
    sub.add_parser("show", parents=[common], help="dump the parsed normalized model as JSON")
    sub.add_parser("diff", parents=[common], help="diff generated inventory against disk without writing")
    sync = sub.add_parser("sync", parents=[common], help="diff generated inventory and write only with --apply")
    sync.add_argument("--apply", action="store_true", help="write files after diff and confirmation")
    sync.add_argument("--yes", action="store_true", help="skip the interactive confirmation (for CI/scripted runs)")
    sub.add_parser("validate", parents=[common], help="run fail-closed invariant checks without writing")
    return parser


def handle_refused(violations: list[str], color: Color, as_json: bool) -> int:
    """Print validation violations and return the refused exit code."""
    if as_json:
        print(json.dumps({"status": "refused", "violations": violations}, indent=2, sort_keys=True))
    else:
        for violation in violations:
            print(color.red(f"REFUSED: {violation}"), file=sys.stderr)
    return 2


def main(argv: list[str]) -> int:
    """Run the sheet_sync command-line interface."""
    parser = build_parser()
    args = parser.parse_args(argv)
    color = Color(enabled=(not args.no_color and sys.stdout.isatty()))
    root = Path(args.root)

    if not DEFAULT_SPREADSHEET_ID:
        print(
            color.red(
                "REFUSED: no spreadsheet configured. Set SHEET_SYNC_SPREADSHEET_ID to the "
                "planning sheet for the site you are rendering."
            ),
            file=sys.stderr,
        )
        return 2

    # Only the inventory-rendering actions need a site; tabs/show/validate read
    # the sheet without writing anything under inventories/<site>/.
    if args.action in {"diff", "sync"} and not args.env:
        print(
            color.red(
                "REFUSED: --env is required. An implicit default makes it easy to render "
                "the wrong site, the same reason ansible.cfg sets no default inventory."
            ),
            file=sys.stderr,
        )
        return 2

    service = build_sheets_service(DEFAULT_CLIENT_SECRET, DEFAULT_TOKEN)

    if args.action == "tabs":
        tabs = list_tabs(service, DEFAULT_SPREADSHEET_ID)
        if args.json:
            print(json.dumps(tabs, indent=2, sort_keys=True))
        else:
            for tab in tabs:
                print(tab)
        return 0

    model = fetch_model(service, DEFAULT_SPREADSHEET_ID)
    violations = validate(model)
    if args.action == "show":
        print_warnings(model.warnings, color)
        if violations:
            print_warnings([f"validation violation: {item}" for item in violations], color)
        print(json.dumps(to_plain_model(model), indent=2, sort_keys=True))
        return 0

    if args.action == "validate":
        print_warnings(model.warnings, color)
        if violations:
            return handle_refused(violations, color, args.json)
        if args.json:
            print(json.dumps({"status": "ok", "warnings": model.warnings}, indent=2, sort_keys=True))
        else:
            print("validation ok")
        return 0

    print_warnings(model.warnings, color)
    if violations:
        return handle_refused(violations, color, args.json)

    rendered = render_inventory_tree(model, args.env)
    changed, diff_text = render_diff(root, rendered, color)
    if diff_text:
        print(diff_text, end="")
    else:
        print("No differences.")

    if args.action == "diff":
        return 1 if changed else 0

    if args.action == "sync":
        if not args.apply:
            print("sync without --apply behaves exactly like diff; no files written.")
            return 1 if changed else 0
        if not changed:
            print("No files written.")
            return 0
        if not confirm_apply(assume_yes=getattr(args, "yes", False)):
            print("Aborted; no files written.", file=sys.stderr)
            return 1
        return write_files(root, rendered)

    raise SystemExit(f"ERROR: unknown action {args.action!r}")


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
