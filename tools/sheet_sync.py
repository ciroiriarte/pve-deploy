#!/usr/bin/env python3
"""
sheet_sync.py - Generate the committed Ansible inventory for pve-deploy from Google Sheets.

Purpose
-------
This tool reads the deployment Google Sheet declared as the single source of truth and renders a
deterministic Ansible inventory under inventories/<env>/, without modifying files unless explicitly
requested. It is intended for the pve-deploy repository used to automate Proxmox VE deployment.

Design rules enforced
---------------------
* Google Sheets is authoritative; generated inventory files are reproducible artifacts.
* The "Logical Networking Table" tab is parsed as a transposed matrix, not as a normal table.
* Only server hardware is emitted as Ansible hosts. The script classifies:
  - hostnames containing "-pve-" as Proxmox VE HCI hosts in group "pve";
  - hostnames containing "-bkp-" or "-pbs-" as Proxmox Backup Server hosts in group "pbs";
  - other Lenovo ThinkSystem rows as physical servers with host_vars and BMC entries, but no
    service group unless a known role is inferred.
* BMC inventory entries are keyed as "<hostname>-bmc" and use ansible_connection: local.
* Network role-to-bond mappings come from role rows in "Logical Networking Table" such as
  "hci (Proxmox VE)" and "bkp (Backup Server)".
* Cabling "Aggregation" is treated as the desired bond name. "OS Device" is treated as
  the live operating-system interface name once populated by hardware discovery.
* Broken spreadsheet formula values such as "#VALUE!" are warnings unless they are used by the
  generated inventory or by validation-critical fields, where they fail closed.

SAFETY
------
Read-only by default. "diff" and "sync" both render the complete target tree and print a unified diff
against disk. "sync" without "--apply" behaves exactly like "diff". "sync --apply" still prompts for
interactive confirmation before writing; pass "--yes" to skip the prompt in CI or scripted runs. A
non-TTY run without "--yes" refuses rather than writing, so a pipeline cannot mutate the inventory by
accident. The tool writes only files it generates and never deletes unknown files.

Usage examples
--------------
  tools/sheet_sync.py tabs
  tools/sheet_sync.py show --json
  tools/sheet_sync.py validate
  tools/sheet_sync.py diff --root /path/to/site-repo --env <site>
  tools/sheet_sync.py sync --root /path/to/site-repo --env <site> --apply

Environment overrides
---------------------
  SHEET_SYNC_SPREADSHEET_ID   Spreadsheet ID. Required; there is no default.
  SHEET_SYNC_CLIENT_SECRET    Desktop OAuth client JSON path. Defaults to client_secret.json
  SHEET_SYNC_TOKEN            Cached OAuth token JSON path. Defaults to token.json

Authentication
--------------
Credentials are resolved by preferring gcloud Application Default Credentials via google.auth.default,
then falling back to an InstalledAppFlow Desktop OAuth client using client_secret.json plus token.json.
The OAuth scope is https://www.googleapis.com/auth/spreadsheets.
"""

